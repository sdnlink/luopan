const FS_PALACE_ORDER = ['坎', '艮', '震', '巽', '离', '坤', '兑', '乾'];

/**
 * 按宫位 key 获取该方位的风水详解数据
 * @param {string} palaceKey 形如 '坎' 或 '坎宫'
 * @returns {object} 宫位数据，取不到时回退为坎宫
 */
function getFengshuiOrientationInfo(palaceKey) {
  if (!palaceKey) return FENGSHUI_PALACES_DATA['坎'];
  const pureKey = String(palaceKey).replace('宫', '').trim();
  return FENGSHUI_PALACES_DATA[pureKey] || FENGSHUI_PALACES_DATA['坎'];
}

